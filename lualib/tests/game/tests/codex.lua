-- fe.codex and the menu's Journal page.
local codex = require("fe.codex")
local data = require("fe.data")
local event = require("fe.event")
local input = require("fe.input")
local menu = require("fe.ui.screens.menu")
local quest = require("fe.quest")
local scene = require("fe.scene")
local state = require("fe.state")
local task = require("fe.task")

local function press(t, key)
  fe.input.feed(key, 1)
  t.tick(1)
  fe.input.feed(key, 0)
  t.tick(2)
end

return {
  ["codex entries load from data, unlock once and are saved"] = function(t)
    state.reset()
    codex.load("data/journal.json")
    t.eq(#codex.entries(), 4)
    t.eq(codex.tabs(), { "objectives", "evidence", "people", "notes" }, "data tabs follow the built-in ones")
    t.eq(codex.tab_name("people"), "People")
    t.eq(codex.tab_name("rumours"), "Rumours")
    local changed = {}
    local disconnect = codex.changed:connect(function(id) changed[#changed + 1] = id end)
    t.eq(codex.unlock("record"), true)
    t.eq(codex.unlock("record"), false, "unlocking again changes nothing")
    t.eq(codex.unlock("notice"), true)
    disconnect()
    t.eq(changed, { "record", "notice" })
    local ids = {}
    for _, entry in ipairs(codex.unlocked("evidence")) do ids[#ids + 1] = entry.id end
    t.eq(ids, { "notice", "record" }, "listed in data order")
    t.eq(#codex.unlocked("people"), 0)
    t.eq({ codex.count() }, { 2, 3 }, "optional entries count once found")
    t.error(function() codex.unlock("nope") end, "no journal entry")
    t.ok(event.matches({ when = { codex = "notice" } }, {}))
    t.ok(not event.matches({ when = { codex = { "notice", "guide" } } }, {}))
    local snapshot = state.snapshot()
    state.reset()
    t.ok(not codex.is_unlocked("notice"))
    state.restore(snapshot)
    t.ok(codex.is_unlocked("notice"))
    state.reset()
  end,

  ["the journal page shows objectives and unlocked entries by tab"] = function(t)
    input.use_defaults()
    state.reset()
    scene.clear()
    codex.load("data/journal.json")
    data.load("quests", "data/quests.json", "quest")
    quest.start("beacon")
    codex.unlock("guide")
    codex.unlock("record")
    local job = task.spawn(menu.journal_page)
    t.tick(1)
    local view = menu.journal_view
    t.eq(view.tab, "objectives")
    t.eq(view.list.items[1].label, "Light the Beacon")
    t.ok(view.list.items[1].detail:find("Open the annex door", 1, true), "objectives are in the detail")
    press(t, "key:E")
    t.eq(view.tab, "evidence")
    t.eq(view.list.items[1].label, "Pressure record")
    t.eq(view.list.items[1].image, "sprites/walker.png", "an entry's image is shown with it")
    view:draw()
    press(t, "key:Right")
    t.eq(view.tab, "people")
    t.eq(view.list.items[1].detail, "Knows the trail.")
    press(t, "key:Right")
    t.eq(view.tab, "notes")
    t.eq(view.list.items[1].enabled, false, "nothing found yet")
    press(t, "key:Right")
    t.eq(view.tab, "objectives", "tabs wrap around")
    press(t, "key:Escape")
    t.eq(job.status, "done")
    local saved = {}
    for i, page in ipairs(menu.pages) do saved[i] = page end
    local page = menu.use_journal()
    t.eq(page.id, "journal")
    t.eq(menu.page("quests"), nil, "the journal takes the quests page's place")
    t.eq(menu.use_journal(), page, "only once")
    for i = #menu.pages, 1, -1 do menu.pages[i] = nil end
    for i, p in ipairs(saved) do menu.pages[i] = p end
    state.reset()
    scene.clear()
  end,
}
