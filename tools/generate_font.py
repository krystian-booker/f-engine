CELL_W, CELL_H, COLS = 6, 10, 16


def png(path, width, height, pixels):
    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))
    rows = b"".join(b"\0" + bytes(pixels[y * width * 4:(y + 1) * width * 4]) for y in range(height))
    path.write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)) +
                     chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b""))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    glyphs = sorted(G.items(), key=lambda item: ord(item[0]))
    rows = (len(glyphs) + COLS - 1) // COLS
    width, height = 128, 64
    while COLS * CELL_W > width:
        width *= 2
    while rows * CELL_H > height:
        height *= 2
    pixels = bytearray(width * height * 4)
    lines = ['info face="fengine pixel" size=10 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0',
             f"common lineHeight={CELL_H} base=8 scaleW={width} scaleH={height} pages=1 packed=0",
             'page id=0 file="pixel.png"', f"chars count={len(glyphs)}"]
    for index, (char, pattern) in enumerate(glyphs):
        ox, oy = (index % COLS) * CELL_W, (index // COLS) * CELL_H
        for y, row in enumerate(pattern):
            for x, cell in enumerate(row):
                if cell == "#":
                    i = ((oy + y + 1) * width + ox + x) * 4
                    pixels[i:i + 4] = b"\xff\xff\xff\xff"
        advance = 4 if char == " " else CELL_W
        lines.append(f"char id={ord(char)} x={ox} y={oy} width={CELL_W} height={CELL_H} xoffset=0 yoffset=0 "
                     f"xadvance={advance} page=0 chnl=15")
    png(OUT / "pixel.png", width, height, pixels)
    (OUT / "pixel.fnt").write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUT / 'pixel.fnt'} ({len(glyphs)} glyphs, {width}x{height})")


if __name__ == "__main__":
    main()
